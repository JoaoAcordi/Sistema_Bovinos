CREATE TABLE movimentacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boi_id BIGINT NOT NULL REFERENCES bois(id),
    piquete_origem_id BIGINT NOT NULL REFERENCES piquetes(id),
    piquete_destino_id BIGINT NOT NULL REFERENCES piquetes(id),
    data_movimentacao DATE NOT NULL,
    motivo VARCHAR(255) NOT NULL
);
